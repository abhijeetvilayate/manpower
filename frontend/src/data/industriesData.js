export const getIndustriesData = () => {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('adminIndustries');
    if (saved) {
      try {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed.map(item => {
            const itemName = item.name || item.title || '';
            const matchedDefault = INDUSTRIES_DATA.find(d => d && (d.name || d.title) && ((d.name || d.title).toLowerCase() === itemName.toLowerCase()));
            return {
              ...item,
              name: itemName,
              title: itemName,
              jobCategories: (item.jobCategories && item.jobCategories.length > 0)
                ? item.jobCategories
                : (item.trades && item.trades.length > 0 
                  ? item.trades 
                  : (matchedDefault ? matchedDefault.jobCategories : []))
            };
          });
        }
      } catch (e) {
        console.error('Error parsing adminIndustries from localStorage', e);
      }
    }
  }
  return INDUSTRIES_DATA;
};
