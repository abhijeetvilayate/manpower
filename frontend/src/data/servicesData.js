export const getServicesData = () => {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('adminServices');
    if (saved) {
      try {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed.map(item => {
            const matchedDefault = SERVICES_DATA.find(d => d && d.title && (d.title.toLowerCase() === (item.title || item.name || '').toLowerCase()));
            return {
              ...item,
              title: item.title || item.name,
              name: item.title || item.name,
              subServices: (item.subServices && item.subServices.length > 0) 
                ? item.subServices 
                : (matchedDefault ? matchedDefault.subServices : [])
            };
          });
        }
      } catch (e) {
        console.error('Error parsing adminServices from localStorage', e);
      }
    }
  }
  return SERVICES_DATA;
};
